import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { REPO_ROOT } from "#src/repo-paths";

const GCC_REGEX = /\bgcc\b/;
const GPP_REGEX = /\bg\+\+\b/;
const MAKE_REGEX = /\bmake\b/;

function readInfraFile(relativePath: string): string {
  return readFileSync(join(REPO_ROOT, "infra", relativePath), "utf8");
}

function shVar(name: string): string {
  return ["$", "{", name, "}"].join("");
}

describe("Server Provisioning Contract (BR-SRV-01..11)", () => {
  const cmdProvision = readInfraFile("scripts/lib/cmd-provision.sh");
  const cmdInit = readInfraFile("scripts/lib/cmd-init.sh");
  const pathsSh = readInfraFile("scripts/lib/paths.sh");
  const composeProd = readInfraFile("docker-compose.prod.yml");
  const ecosystem = readInfraFile("pm2/ecosystem.config.cjs");
  const logrotate = readInfraFile("pm2/logrotate.conf");

  it("BR-SRV-01: provisioning steps check existing state before installing or enabling", () => {
    expect(cmdProvision).toContain(`if [ -f "${shVar("MK_SWAP_FILE")}" ]`);
    expect(cmdProvision).toContain("if ! command -v pnpm");
    expect(cmdProvision).toContain("if ! command -v docker");
    expect(cmdProvision).toContain("if ! command -v pm2");
    expect(cmdInit).toContain(`if ! id "${shVar("MK_SYSTEM_USER")}"`);
  });

  it("BR-SRV-02: system user mindkid has nologin shell and PM2 drops apps to mindkid uid/gid", () => {
    expect(pathsSh).toContain(
      `MK_SYSTEM_USER="${shVar("MK_SYSTEM_USER:-mindkid")}"`
    );
    expect(cmdInit).toContain(
      `useradd --system --shell /usr/sbin/nologin --home-dir "${shVar("MK_ROOT")}" --create-home "${shVar("MK_SYSTEM_USER")}"`
    );
    expect(ecosystem).toContain('uid: "mindkid"');
    expect(ecosystem).toContain('gid: "mindkid"');
  });

  it("BR-SRV-03: PostgreSQL and Valkey bind exclusively to 127.0.0.1 loopback", () => {
    expect(composeProd).toContain('"127.0.0.1:5432:5432"');
    expect(composeProd).toContain('"127.0.0.1:6379:6379"');
    expect(composeProd).not.toContain('"5432:5432"');
    expect(composeProd).not.toContain('"6379:6379"');
    expect(composeProd).not.toContain("0.0.0.0");
  });

  it("BR-SRV-04: UFW denies incoming by default and opens only 22, 80, 443", () => {
    expect(cmdProvision).toContain("ufw default deny incoming");
    expect(cmdProvision).toContain("ufw default allow outgoing");
    expect(cmdProvision).toContain("for port in 22 80 443; do");
    expect(cmdProvision).not.toContain("3000/tcp");
    expect(cmdProvision).not.toContain("3099/tcp");
    expect(cmdProvision).not.toContain("5432/tcp");
    expect(cmdProvision).not.toContain("6379/tcp");
  });

  it("BR-SRV-05: enforces exact major versions (Node 24, pnpm 11, PostgreSQL 17, Valkey 9) and stops on drift", () => {
    expect(pathsSh).toContain("MK_NODE_MAJOR=24");
    expect(pathsSh).toContain("MK_PNPM_MAJOR=11");
    expect(pathsSh).toContain("MK_POSTGRES_MAJOR=17");
    expect(pathsSh).toContain("MK_VALKEY_MAJOR=9");
    expect(composeProd).toContain("pgvector/pgvector:pg17");
    expect(composeProd).toContain("valkey/valkey:9-bookworm");
    expect(cmdProvision).toContain("Not upgrading automatically.");
    expect(cmdProvision).toContain("drift) return 1 ;;");
  });

  it("BR-SRV-06: /etc/mindkid/env is owned by root:root with mode 0700 and never generated by provision", () => {
    expect(pathsSh).toContain(
      `MK_ENV_DIR="${shVar("MK_ENV_DIR:-/etc/mindkid/env")}"`
    );
    expect(cmdInit).toContain(`chown root:root "${shVar("MK_ENV_DIR")}"`);
    expect(cmdInit).toContain(`chmod 0700 "${shVar("MK_ENV_DIR")}"`);
    expect(cmdProvision).toContain("mode 0600 root:root");
  });

  it("BR-SRV-07: provision never deletes or overwrites env files, database volumes, or release history", () => {
    expect(cmdProvision).not.toContain("docker volume rm");
    expect(cmdProvision).not.toContain("down -v");
    expect(cmdProvision).not.toContain(`rm -f "${shVar("MK_ENV_DIR")}`);
    expect(cmdProvision).not.toContain(`rm -rf "${shVar("MK_RELEASES_DIR")}`);
    expect(cmdProvision).not.toContain(`rm -rf "${shVar("MK_BACKUP_DIR")}`);
  });

  it("BR-SRV-08: enables certbot.timer and reloads nginx via deploy-hook on renewal", () => {
    expect(cmdProvision).toContain("systemctl enable --now certbot.timer");
    expect(cmdProvision).toContain("--deploy-hook 'systemctl reload nginx'");
  });

  it("BR-SRV-09: logrotate bounds /var/log/mindkid logs with daily rotation, 14 retention, and maxsize 200M", () => {
    expect(logrotate).toContain("/var/log/mindkid/*/*.log");
    expect(logrotate).toContain("daily");
    expect(logrotate).toContain("rotate 14");
    expect(logrotate).toContain("maxsize 200M");
    expect(logrotate).toContain("pm2 reloadLogs");
  });

  it("BR-SRV-10: prints final version summary report at end of provisioning", () => {
    expect(cmdProvision).toContain("mk_prov_report()");
    expect(cmdProvision).toContain("Node       %s");
    expect(cmdProvision).toContain("pnpm       %s");
    expect(cmdProvision).toContain("PostgreSQL %s");
    expect(cmdProvision).toContain("Valkey     %s");
    expect(cmdProvision).toContain("pg_dump    %s");
  });

  it("BR-SRV-11: does not install compiler toolchains (build-essential, gcc, g++, make, python3-dev) on host", () => {
    expect(cmdProvision).not.toContain("build-essential");
    expect(cmdProvision).not.toContain("python3-dev");
    expect(cmdProvision).not.toMatch(GCC_REGEX);
    expect(cmdProvision).not.toMatch(GPP_REGEX);
    expect(cmdProvision).not.toMatch(MAKE_REGEX);
  });
});
