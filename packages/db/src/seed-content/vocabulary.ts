import { CANONICAL_THEME_CODES } from "@mindkid/shared";

const THEME_TAGS = [...CANONICAL_THEME_CODES];

const TAG_SET_BY_AXIS: Record<string, Set<string>> = {
  what: new Set(WHAT_TAGS),
  thinking: new Set(THINKING_TAGS),
  mechanic: new Set(MECHANIC_TAGS),
  theme: new Set(THEME_TAGS),
};

export function isValidTagForAxis(
  axis: "what" | "thinking" | "mechanic" | "theme",
  tag: string
): boolean {
  if (!tag || tag.trim().length === 0) {
    return false;
  }
  const set = TAG_SET_BY_AXIS[axis];
  return set?.has(tag) ?? false;
}
