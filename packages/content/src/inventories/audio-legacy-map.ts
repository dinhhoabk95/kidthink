export const AUDIO_LEGACY_BY_PATH: ReadonlyMap<string, AudioLegacyAsset> =
  new Map(AUDIO_LEGACY_INVENTORY.map((item) => [item.path, item]));

export function isValidAudioPath(path: string): boolean {
  return AUDIO_LEGACY_BY_PATH.has(path);
}

export function getAudioByPath(path: string): AudioLegacyAsset | undefined {
  return AUDIO_LEGACY_BY_PATH.get(path);
}

export function getAudiosForSkill(
  skillOrStrand: string
): readonly AudioLegacyAsset[] {
  return AUDIO_LEGACY_INVENTORY.filter((item) =>
    item.target_skill_or_strand?.startsWith(skillOrStrand)
  );
}
